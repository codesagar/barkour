"""Copy the lossless runtime sheets and derive browser data from the source manifests."""
import json
import shutil
from pathlib import Path

root = Path(__file__).resolve().parents[1]
packs = []
for name in ('buddy', 'neet'):
    source = root / 'new-assets' / name
    manifest = json.loads((source / f'{name}.animations.json').read_text())
    target = root / 'assets' / 'characters' / name
    target.mkdir(parents=True, exist_ok=True)
    animations = {}
    for clip, data in manifest['animations'].items():
        resolution = '512' if clip == 'idle' else '256'
        filename = f'{clip}.webp' if resolution == '512' else f'{clip}-256.webp'
        shutil.copyfile(source / resolution / f'{clip}.webp', target / filename)
        animations[clip] = {key: data[key] for key in ('columns', 'frameCount', 'durationsMs', 'loop')}
        animations[clip]['sheet'] = f'assets/characters/{name}/{filename}'
        animations[clip]['sheetScale'] = int(resolution) / manifest['frameSize']['w']
    # Physics comes from js/pet-manifest.js. These values describe only how a
    # pack is presented around the common paw root.
    presentation = {
        'buddy': {'visualBounds': {'x': 82, 'y': 72, 'w': 365, 'h': 387}, 'focusPoint': {'x': 256, 'y': 258}, 'tags': ['medium']},
        'neet': {'visualBounds': {'x': 95, 'y': 65, 'w': 338, 'h': 394}, 'focusPoint': {'x': 258, 'y': 250}, 'tags': ['medium', 'fluffy']}
    }[name]
    packs.append({
        'schemaVersion': 1, 'assetId': name, 'displayName': manifest['character'],
        # name/pivot are retained for existing local integrations; runtime code
        # reads the stable metadata above and the canonical body from the manifest.
        'name': manifest['character'], 'frameSize': manifest['frameSize'], 'pawRoot': manifest['pivot'], 'pivot': manifest['pivot'],
        'visualBounds': presentation['visualBounds'], 'focusPoint': presentation['focusPoint'],
        'presentation': {'scale': 1, 'baselineOffset': 0}, 'gameplayBodyId': 'equal-pet-v1', 'tags': presentation['tags'],
        'animations': animations, 'states': manifest['states']
    })
(root / 'js' / 'character-assets.js').write_text(
    '// Generated by scripts/prepare-characters.py. Frame order is already baked into the sheets.\n'
    '// Embedded metadata also supports opening index.html directly without fetch/file CORS.\n'
    'const CHARACTER_ASSETS = ' + json.dumps(packs, indent=2) + ';\n'
)
